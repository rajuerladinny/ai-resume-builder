"""Writes the files the frontend shares with this backend.

    python -m app.export_shared

- frontend/src/lib/vocab.js: the skill, alias and stopword lists
- fixtures/parity.json: inputs with this backend's results, which the
  JavaScript ports used by the in-browser demo must reproduce exactly

Run it after changing keywords.py, checks.py or tailor.py.
tests/test_shared.py fails when either file is out of date.
"""
import json
from pathlib import Path

from . import checks, keywords, tailor

ROOT = Path(__file__).resolve().parents[2]
VOCAB_PATH = ROOT / "frontend" / "src" / "lib" / "vocab.js"
SAMPLE_PATH = ROOT / "frontend" / "src" / "lib" / "sample.js"
JS_PREFIX = "export default "
VOCAB_HEADER = "// Generated by `python -m app.export_shared` from backend/app/keywords.py. Do not edit.\n"
PARITY_PATH = ROOT / "fixtures" / "parity.json"

EXTRA_CASES = [
    {
        "name": "tech tokens and aliases",
        "resume": "I am responsible for C++/C#, .NET, CI/CD and k8s. My node.js/React.js APIs. "
        "Worked on RESTful microservices, springboot and LLMs.\n1. Did 3 things\n* no numbers",
        "job": "C++ C# .NET ci/cd Kubernetes Node.js React REST API microservices Spring Boot "
        "LLM llm. Kubernetes clusters, clusters, 2024 2024, payments Payments PAYMENTS.",
    },
    {"name": "empty job", "resume": "Plain resume text with nothing special.", "job": ""},
    {
        "name": "half-point scores",
        "resume": "react",
        "job": "react typescript python java golang docker aws redis",
    },
]


def vocab() -> dict:
    return {
        "skills": sorted(keywords.SKILLS),
        "aliases": dict(sorted(keywords.ALIASES.items())),
        "stopwords": sorted(keywords.STOPWORDS),
    }


def parity() -> dict:
    sample = read_js(SAMPLE_PATH)
    cases = [
        {"name": "sample", "resume": sample["resume"], "job": sample["job"]},
        {"name": "sample tailored", "resume": sample["tailored"], "job": sample["job"]},
        *EXTRA_CASES,
    ]
    for case in cases:
        case["analyze"] = keywords.analyze(case["resume"], case["job"])
        case["keywords"] = keywords.extract_keywords(case["job"])
        case["review"] = checks.review(case["resume"])
    return {
        "cases": cases,
        "sample_check": tailor.invented_terms(sample["resume"], sample["tailored"], sample["job"]),
    }


def read_js(path: Path) -> dict:
    """Read a module of the form `export default <JSON>;`."""
    text = path.read_text(encoding="utf-8")
    body = text[text.index(JS_PREFIX) + len(JS_PREFIX) :].strip().removesuffix(";")
    return json.loads(body)


def render(data: dict) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def render_vocab() -> str:
    return VOCAB_HEADER + JS_PREFIX + render(vocab()).rstrip("\n") + ";\n"


def main() -> None:
    VOCAB_PATH.write_text(render_vocab(), encoding="utf-8")
    PARITY_PATH.parent.mkdir(exist_ok=True)
    PARITY_PATH.write_text(render(parity()), encoding="utf-8")
    print(f"Wrote {VOCAB_PATH.relative_to(ROOT)} and {PARITY_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
